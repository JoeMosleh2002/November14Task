-- Task 1: TRIM, LTRIM, RTRIM | Oracle SQL
-- Run in a schema where EMP_TEST does not already exist.
-- Q1
CREATE TABLE EMP_TEST (NAME VARCHAR2(100));
INSERT INTO EMP_TEST (NAME) VALUES ('   Ahmed   ');
INSERT INTO EMP_TEST (NAME) VALUES ('  Mona');
INSERT INTO EMP_TEST (NAME) VALUES ('Sara   ');
COMMIT;
-- Q2
SELECT NAME AS ORIGINAL_NAME, TRIM(NAME) AS TRIMMED_NAME FROM EMP_TEST;
-- Q3
SELECT NAME AS ORIGINAL_NAME, LTRIM(NAME) AS LEFT_TRIMMED FROM EMP_TEST;
-- Q4
SELECT NAME AS ORIGINAL_NAME, RTRIM(NAME) AS RIGHT_TRIMMED FROM EMP_TEST;
-- Q5
SELECT TRIM(BOTH '*' FROM '**Oracle SQL**') AS TRIMMED_STARS FROM DUAL;
