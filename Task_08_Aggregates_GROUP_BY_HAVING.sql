-- Task 8: 18 aggregate function exercises | Oracle SQL
-- PREREQUISITE: An existing EMPLOYEES table with SALARY, EMPLOYEE_ID,
-- DEPARTMENT_ID, JOB_ID, MANAGER_ID, COMMISSION_PCT columns.
-- The common Oracle HR.EMPLOYEES table has these columns. No table is created here.
-- Q1 AVG
SELECT AVG(SALARY) AS AVG_SALARY FROM EMPLOYEES;
-- Q2 COUNT
SELECT COUNT(*) AS EMPLOYEE_COUNT FROM EMPLOYEES;
-- Q3 MAX
SELECT MAX(SALARY) AS MAX_SALARY FROM EMPLOYEES;
-- Q4 MIN
SELECT MIN(SALARY) AS MIN_SALARY FROM EMPLOYEES;
-- Q5 SUM
SELECT SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES;
-- Q6 GROUP BY department
SELECT DEPARTMENT_ID, AVG(SALARY) AS AVG_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT_ID;
-- Q7 GROUP BY job
SELECT JOB_ID, COUNT(*) AS EMPLOYEE_COUNT FROM EMPLOYEES GROUP BY JOB_ID;
-- Q8 HAVING salary sum > 50000
SELECT DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES
GROUP BY DEPARTMENT_ID HAVING SUM(SALARY) > 50000;
-- Q9 AVG non-null commissions
SELECT AVG(COMMISSION_PCT) AS AVG_COMMISSION FROM EMPLOYEES WHERE COMMISSION_PCT IS NOT NULL;
-- Q10 COUNT salaries > 10000
SELECT COUNT(*) AS HIGH_SALARY_EMPLOYEES FROM EMPLOYEES WHERE SALARY > 10000;
-- Q11 MAX and MIN per job
SELECT JOB_ID, MAX(SALARY) AS MAX_SALARY, MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES GROUP BY JOB_ID;
-- Q12 salary sum per manager
SELECT MANAGER_ID, SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES GROUP BY MANAGER_ID;
-- Q13 department and job
SELECT DEPARTMENT_ID, JOB_ID, SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES GROUP BY DEPARTMENT_ID, JOB_ID;
-- Q14 jobs with > 5 employees
SELECT JOB_ID, COUNT(*) AS EMPLOYEE_COUNT FROM EMPLOYEES
GROUP BY JOB_ID HAVING COUNT(*) > 5;
-- Q15 multiple aggregates per department
SELECT DEPARTMENT_ID, COUNT(*) AS TOTAL_EMPLOYEES, AVG(SALARY) AS AVG_SALARY,
       MAX(SALARY) AS MAX_SALARY, MIN(SALARY) AS MIN_SALARY
FROM EMPLOYEES GROUP BY DEPARTMENT_ID;
-- Q16 average salary > 8000 and count < 10
SELECT DEPARTMENT_ID, AVG(SALARY) AS AVG_SALARY, COUNT(*) AS EMPLOYEE_COUNT
FROM EMPLOYEES GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000 AND COUNT(*) < 10;
-- Q17 highest department total; exclude NULL department identifiers
SELECT DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID ORDER BY TOTAL_SALARY DESC
FETCH FIRST 1 ROW ONLY;
-- Q18 aggregate aliases
SELECT DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SALARY,
       AVG(SALARY) AS AVERAGE_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT_ID;
