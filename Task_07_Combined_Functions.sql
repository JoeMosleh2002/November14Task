-- Task 7: Combined character/date/conditional exercises | Oracle SQL
-- 1. Character functions: TRIM, LTRIM, RTRIM
CREATE TABLE CUSTOMERS (FULL_NAME VARCHAR2(100));
INSERT INTO CUSTOMERS VALUES ('   Ahmed Ali   ');
INSERT INTO CUSTOMERS VALUES ('  Mona Hassan');
INSERT INTO CUSTOMERS VALUES ('Sara Omar   ');
COMMIT;
SELECT FULL_NAME, TRIM(FULL_NAME) AS CLEAN_NAME FROM CUSTOMERS;
SELECT FULL_NAME, LTRIM(FULL_NAME) AS NO_LEADING_SPACES FROM CUSTOMERS;
SELECT FULL_NAME, RTRIM(FULL_NAME) AS NO_TRAILING_SPACES FROM CUSTOMERS;
SELECT TRIM(BOTH '$' FROM '$$Price$$') AS NO_DOLLARS,
       TRIM(BOTH '*' FROM '**Name**') AS NO_STARS,
       TRIM(BOTH '#' FROM '##Code##') AS NO_HASHES FROM DUAL;

-- 2. REPLACE, LPAD, RPAD
SELECT REPLACE('promotion', 'o', '0') AS RESULT FROM DUAL;
SELECT REPLACE('This is a basic course', 'basic', 'advanced') AS RESULT FROM DUAL;
CREATE TABLE DEPARTMENTS (DEPT_NAME VARCHAR2(100));
INSERT INTO DEPARTMENTS VALUES ('HR');
INSERT INTO DEPARTMENTS VALUES ('IT');
INSERT INTO DEPARTMENTS VALUES ('Sales');
COMMIT;
SELECT DEPT_NAME, LPAD(DEPT_NAME, 15, '*') AS LEFT_PADDED FROM DEPARTMENTS;
SELECT DEPT_NAME, RPAD(DEPT_NAME, 15, '-') AS RIGHT_PADDED FROM DEPARTMENTS;

-- 3. TO_CHAR
SELECT TO_CHAR(SYSDATE, 'DD-MON-YYYY', 'NLS_DATE_LANGUAGE=ENGLISH') AS DATE_FORMAT FROM DUAL;
SELECT TO_CHAR(SYSDATE, 'FMDay, FMMonth YYYY', 'NLS_DATE_LANGUAGE=ENGLISH') AS DATE_FORMAT FROM DUAL;
SELECT TO_CHAR(12345.67, 'FM99,999,990.00', 'NLS_NUMERIC_CHARACTERS=''.,''') AS FORMATTED_NUMBER FROM DUAL;
-- Salary example works without an EMPLOYEES table.
SELECT TO_CHAR(12000, 'FML999,999,990.00', 'NLS_CURRENCY=''$'' NLS_NUMERIC_CHARACTERS=''.,''') AS SALARY_WITH_CURRENCY FROM DUAL;
SELECT TO_CHAR(SYSDATE, 'YYYY/MM/DD HH24:MI:SS') AS DATE_TIME FROM DUAL;

-- 4. CASE expressions
-- Separate table from Task 4, so both scripts can be run in the same schema.
CREATE TABLE STUDENTS_TASK7 (NAME VARCHAR2(100), SCORE NUMBER(5,2));
INSERT INTO STUDENTS_TASK7 VALUES ('Ahmed', 95);
INSERT INTO STUDENTS_TASK7 VALUES ('Mona', 85);
INSERT INTO STUDENTS_TASK7 VALUES ('Sara', 75);
INSERT INTO STUDENTS_TASK7 VALUES ('Omar', 65);
INSERT INTO STUDENTS_TASK7 VALUES ('Nour', 55);
COMMIT;
SELECT NAME, SCORE,
       CASE WHEN SCORE >= 90 THEN 'A' WHEN SCORE >= 80 THEN 'B'
            WHEN SCORE >= 70 THEN 'C' ELSE 'F' END AS GRADE
FROM STUDENTS_TASK7;
SELECT NAME, SCORE, CASE WHEN SCORE >= 60 THEN 'Pass' ELSE 'Fail' END AS RESULT
FROM STUDENTS_TASK7;
SELECT NAME, SCORE,
       CASE WHEN SCORE >= 90 THEN 'Excellent'
            WHEN SCORE >= 80 THEN 'Good'
            WHEN SCORE >= 70 THEN 'Average'
            ELSE 'Needs Improvement' END AS MESSAGE
FROM STUDENTS_TASK7;
SELECT 'Today is ' || TRIM(TO_CHAR(SYSDATE, 'Day', 'NLS_DATE_LANGUAGE=ENGLISH')) AS TODAY_MESSAGE FROM DUAL;

-- 5. DECODE
-- This task asks for exact score-value matching, not ranges.
SELECT NAME, SCORE, DECODE(SCORE, 100, 'A', 90, 'B', 80, 'C', 'F') AS GRADE
FROM STUDENTS_TASK7;
CREATE TABLE STATUS_LOG (STATUS_CODE CHAR(1));
INSERT INTO STATUS_LOG VALUES ('N');
INSERT INTO STATUS_LOG VALUES ('I');
INSERT INTO STATUS_LOG VALUES ('C');
COMMIT;
SELECT STATUS_CODE, DECODE(STATUS_CODE, 'N', 'New', 'I', 'In Progress', 'C', 'Completed', 'Unknown') AS STATUS_DESCRIPTION FROM STATUS_LOG;
SELECT PRODUCT_NAME, QUANTITY,
       DECODE(QUANTITY, 0, 'Out of Stock', 'Available') AS STOCK_STATUS
FROM (SELECT 'Keyboard' AS PRODUCT_NAME, 0 AS QUANTITY FROM DUAL
      UNION ALL SELECT 'Mouse', 15 FROM DUAL);
SELECT DEPT_NAME, DECODE(DEPT_NAME, 'HR', 500, 'IT', 1000, 'Sales', 1500, 300) AS BONUS
FROM DEPARTMENTS;
