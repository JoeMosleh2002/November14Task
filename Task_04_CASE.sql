-- Q3
SELECT NAME, MARKS,
       CASE WHEN MARKS >= 90 THEN 'A'
            WHEN MARKS >= 80 THEN 'B'
            WHEN MARKS >= 70 THEN 'C'
            ELSE 'F' END AS GRADE
FROM STUDENTS;
