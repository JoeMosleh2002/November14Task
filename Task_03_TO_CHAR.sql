-- Task 3: TO_CHAR | Oracle SQL
-- Q1
SELECT TO_CHAR(SYSDATE, 'DD-MON-YYYY', 'NLS_DATE_LANGUAGE=ENGLISH') AS CURRENT_DATE_FORMATTED FROM DUAL;
-- Q2
SELECT TO_CHAR(SYSDATE, 'FMMonth YYYY', 'NLS_DATE_LANGUAGE=ENGLISH') AS MONTH_YEAR FROM DUAL;
-- Q3
SELECT TO_CHAR(12345.67, 'FM99,999,990.00', 'NLS_NUMERIC_CHARACTERS=''.,''') AS FORMATTED_NUMBER FROM DUAL;
-- Q4: standalone example, no pre-existing table required
SELECT TO_CHAR(15000, 'FML999,999,990.00', 'NLS_CURRENCY=''$'' NLS_NUMERIC_CHARACTERS=''.,''') AS FORMATTED_SALARY FROM DUAL;
